package nebula

import (
	"errors"
	"fmt"
	"reflect"
	"testing"

	ng "github.com/vesoft-inc/nebula-go/v3"
	nv "github.com/vesoft-inc/nebula-go/v3/nebula"
	gr "github.com/vesoft-inc/nebula-go/v3/nebula/graph"
)

func metadataResult(t *testing.T, columns []string, values ...*nv.Value) *ng.ResultSet {
	t.Helper()
	names := make([][]byte, len(columns))
	for i, column := range columns {
		names[i] = []byte(column)
	}
	rs, err := ng.GenResultSet(&gr.ExecutionResponse{
		ErrorCode: nv.ErrorCode_SUCCEEDED,
		Data:      &nv.DataSet{ColumnNames: names, Rows: []*nv.Row{{Values: values}}},
	})
	if err != nil {
		t.Fatal(err)
	}
	return rs
}

// Independent protocol values reproduce the 3.8.0 metadata shape. They are not
// generated by the decoder or the graph adapter being tested.
func TestSDKMetadataEmptyValues(t *testing.T) {
	str := func(s string) *nv.Value { return &nv.Value{SVal: []byte(s)} }
	num := int64(10)
	spaceColumns := []string{
		"ID", "Name", "Partition Number", "Replica Factor", "Charset", "Collate", "Vid Type",
		"Comment",
	}
	spaceValues := []*nv.Value{
		{IVal: &num},
		str("primind_ng_contract"),
		{IVal: &num},
		{IVal: &num},
		str("utf8"),
		str("utf8_bin"), str("FIXED_STRING(1024)"),
		{},
	}
	t.Run("space absent comment", func(t *testing.T) {
		got, err := decodeSDKTable(metadataResult(t, spaceColumns, spaceValues...), DefaultConfig())
		want := []string{"10", "primind_ng_contract", "10", "10", "utf8", "utf8_bin", "FIXED_STRING(1024)", ""}
		if err != nil || len(got.Rows) != 1 || !reflect.DeepEqual(got.Rows[0], want) {
			t.Fatalf("metadata mismatch: table=%+v err=%v", got, err)
		}
	})
	t.Run("definition absent default and comment", func(t *testing.T) {
		got, err := decodeSDKTable(metadataResult(t, []string{"Field", "Type", "Null", "Default", "Comment"}, str("kb"),
			str("string"), str("NO"), &nv.Value{}, &nv.Value{}), DefaultConfig())
		if err != nil || len(got.Rows) != 1 || !reflect.DeepEqual(got.Rows[0], []string{"kb", "string", "NO", "", ""}) {
			t.Fatalf("metadata mismatch: table=%+v err=%v", got, err)
		}
	})
	for _, column := range []string{"name", "attrs", "Vid Type", "Comment"} {
		t.Run("reject empty outside metadata shape "+column, func(t *testing.T) {
			_, err := decodeSDKTable(metadataResult(t, []string{column}, &nv.Value{}), DefaultConfig())
			if !errors.Is(err, ErrInvalid) {
				t.Fatalf("unexpected error: %v", err)
			}
		})
	}
	t.Run("reject empty required metadata", func(t *testing.T) {
		values := append([]*nv.Value(nil), spaceValues...)
		values[6] = &nv.Value{}
		_, err := decodeSDKTable(metadataResult(t, spaceColumns, values...), DefaultConfig())
		if !errors.Is(err, ErrInvalid) {
			t.Fatalf("unexpected error: %v", err)
		}
	})
	t.Run("reject unsupported metadata type", func(t *testing.T) {
		values := append([]*nv.Value(nil), spaceValues...)
		f := 1.5
		values[7] = &nv.Value{FVal: &f}
		_, err := decodeSDKTable(metadataResult(t, spaceColumns, values...), DefaultConfig())
		if !errors.Is(err, ErrInvalid) {
			t.Fatalf("unexpected error: %v", err)
		}
	})
	t.Run("byte budget retained", func(t *testing.T) {
		cfg := DefaultConfig()
		cfg.ReadBytes = 8
		_, err := decodeSDKTable(metadataResult(t, spaceColumns, spaceValues...), cfg)
		if !errors.Is(err, ErrBudget) {
			t.Fatalf("unexpected error: %v", err)
		}
	})
}

func TestSDKMetadataIndexColumns(t *testing.T) {
	str := func(s string) *nv.Value { return &nv.Value{SVal: []byte(s)} }
	list := func(values ...*nv.Value) *nv.Value { return &nv.Value{LVal: &nv.NList{Values: values}} }
	for _, owner := range []string{"By Tag", "By Edge"} {
		t.Run(owner, func(t *testing.T) {
			got, err := decodeSDKTable(metadataResult(t, []string{"Index Name", owner, "Columns"},
				str("primind_entity_scope"), str("primind_entity"), list(str("kb"), str("doc"))), DefaultConfig())
			if err != nil || len(got.Rows) != 1 || got.Rows[0][2] != `["kb","doc"]` {
				t.Fatalf("metadata mismatch: table=%+v err=%v", got, err)
			}
		})
	}
	for _, tc := range []struct {
		name  string
		value *nv.Value
		want  string
	}{
		{"empty", list(), `[]`},
		{"escaping", list(str("名\"\\\n")), `["名\"\\\n"]`},
	} {
		t.Run(tc.name, func(t *testing.T) {
			got, err := decodeSDKTable(metadataResult(t, []string{"Index Name", "By Tag", "Columns"}, str("i"),
				str("t"), tc.value), DefaultConfig())
			if err != nil || len(got.Rows) != 1 || got.Rows[0][2] != tc.want {
				t.Fatalf("metadata mismatch: table=%+v err=%v", got, err)
			}
		})
	}
	n := int64(1)
	for _, tc := range []struct {
		name  string
		value *nv.Value
	}{
		{"integer", list(&nv.Value{IVal: &n})},
		{"nested", list(list(str("kb")))},
		{"empty element", list(&nv.Value{})},
	} {
		t.Run("reject "+tc.name, func(t *testing.T) {
			_, err := decodeSDKTable(metadataResult(t, []string{"Index Name", "By Tag", "Columns"}, str("i"), str("t"),
				tc.value), DefaultConfig())
			if !errors.Is(err, ErrInvalid) {
				t.Fatalf("unexpected error: %v", err)
			}
		})
	}
	t.Run("reject list outside index metadata", func(t *testing.T) {
		_, err := decodeSDKTable(metadataResult(t, []string{"Columns"}, list(str("kb"))), DefaultConfig())
		if !errors.Is(err, ErrInvalid) {
			t.Fatalf("unexpected error: %v", err)
		}
	})
	for _, budget := range []int{1, 4, 6, 13} {
		t.Run(fmt.Sprintf("budget %d", budget), func(t *testing.T) {
			cfg := DefaultConfig()
			cfg.ReadBytes = budget
			_, err := decodeSDKTable(metadataResult(t, []string{"Index Name", "By Tag", "Columns"}, str("i"), str("t"),
				list(str("kb"), str("doc"))), cfg)
			if !errors.Is(err, ErrBudget) {
				t.Fatalf("unexpected error: %v", err)
			}
		})
	}
}
